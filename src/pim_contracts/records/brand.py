"""
Brand x category landing pages exposed by inventory for storefronts (since 1.28.0).

`GET /api/v1/integrations/santeh24/brand-pages` returns list[MasterBrandPageRecord], computed by PIM from the
storefront products. Storefront route: /catalog/<category_slug>/<slug>/.
Consumers: santeh24.kz frontend/src/lib/pim.ts.
"""
from pydantic import BaseModel, ConfigDict, Field


class MasterBrandPageTranslation(BaseModel):
    """Translated texts of a brand x category page (since 1.28.0)."""

    model_config = ConfigDict(extra="ignore", from_attributes=True)

    h1: str | None = Field(default=None, description="Translated page heading")
    seo_title: str | None = Field(default=None, description="Translated SEO meta title")
    seo_description: str | None = Field(default=None, description="Translated SEO meta description")
    stats_text: str | None = Field(default=None, description="Translated MasterBrandPageRecord.stats_text (since 1.29.0)")


class MasterBrandPageRecord(BaseModel):
    """
    Landing page of one brand inside one leaf category, e.g. Gloria x Hooks (since 1.28.0).

    A pair is listed while it has enough published products; `indexable` follows the in-stock count, so the URL
    stays alive (noindex) when stock drops instead of disappearing. The storefront takes H1 and meta from here.
    """

    model_config = ConfigDict(extra="ignore", from_attributes=True)

    brand: str = Field(..., description="Brand name as on the product cards (MasterProductRecord.brand)")
    brand_slug: str = Field(..., description="Stable URL slug of the brand, generated by PIM")
    previous_brand_slugs: list[str] = Field(
        default_factory=list,
        description="Former slugs of the brand; storefront answers them with 301 to the current page",
    )
    category_slug: str = Field(..., description="Slug of the leaf category (MasterCategoryRecord.slug)")
    slug: str = Field(..., description="Page slug inside the category: 'brand-<brand_slug>'")
    product_count: int = Field(..., ge=0, description="Published products of the pair, out of stock included")
    in_stock_count: int = Field(..., ge=0, description="Published products of the pair in stock")
    price_min: float | None = Field(
        default=None, description="Lowest retail price among in-stock products; null — none in stock"
    )
    price_max: float | None = Field(
        default=None, description="Highest retail price among in-stock products; null — none in stock"
    )
    indexable: bool = Field(
        ..., description="false — storefront renders the page with noindex and leaves it out of the sitemap"
    )
    h1: str = Field(..., description="Page heading in Russian, generated by PIM")
    seo_title: str | None = Field(default=None, description="SEO meta title in Russian")
    seo_description: str | None = Field(default=None, description="SEO meta description in Russian")
    stats_text: str | None = Field(
        default=None,
        description=(
            "Short Russian paragraph with live figures of the pair (models, in stock, price range, common sizes), "
            "generated by PIM on every request; null — too few products in stock (since 1.29.0)"
        ),
    )
    translations: dict[str, MasterBrandPageTranslation] = Field(
        default_factory=dict,
        description="Page text translations keyed by language code, currently only 'kk'",
    )
