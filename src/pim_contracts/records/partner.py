"""
Partner API DTOs: what inventory exposes to external partner stores (since 1.14.0).

Our ecosystem acts as a wholesale supplier for partners (first one: adilux.kz).
A partner gets the product content without our retail price and stock
(PartnerProductRecord) and, separately, our aggregated wholesale offer
(PartnerOfferRecord). Retail prices are set by the partner itself.

PartnerProductRecord repeats the content fields of MasterProductRecord in the
same order; MasterProductRecord is intentionally not refactored onto a shared
base so its field order and serialization stay unchanged. A test keeps the two
in sync.
"""
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field

from pim_contracts.enums import Currency
from pim_contracts.records.product import (
    MasterCharacteristicRecord,
    MasterProductRelation,
    MasterProductTranslation,
)


class PartnerProductRecord(BaseModel):
    """
    Product card content for an external partner (since 1.14.0).

    Same as MasterProductRecord without retail price and stock:
    no price, price_updated_at, cost_price, stock, stock_quantity.
    The offer for the product is PartnerOfferRecord.
    """

    model_config = ConfigDict(extra="ignore", from_attributes=True)

    id: int = Field(..., description="Internal product primary key")
    name: str = Field(..., description="Resolved product name (PIM name, else base name)")
    slug: str | None = Field(
        default=None,
        description="Product URL slug built by PIM from pim_name when the admin saves the card",
    )
    previous_slugs: list[str] = Field(
        default_factory=list,
        description="Former slugs of this product; a partner may redirect them to the current slug",
    )
    mpn: str | None = Field(default=None, description="Manufacturer part number")
    gpc_id: int | None = Field(default=None, description="Google product category ID")
    brand: str | None = Field(default=None, description="Brand name")
    shipping_weight: str | None = Field(default=None, description="Shipping weight")
    shipping_length: str | None = Field(default=None, description="Shipping length")
    shipping_width: str | None = Field(default=None, description="Shipping width")
    shipping_height: str | None = Field(default=None, description="Shipping height")
    shipping_dimension_unit: str | None = Field(
        default=None,
        description="Unit of shipping_length/width/height, e.g. 'cm'",
    )
    shipping_weight_unit: str | None = Field(
        default=None,
        description="Unit of shipping_weight, e.g. 'kg'",
    )
    category: str | None = Field(default=None, description="Category name")
    category_slug: str | None = Field(
        default=None,
        description="Stable URL slug of the product category (owned by PIM)",
    )
    description: str | None = Field(default=None, description="Resolved product description")
    seo_title: str | None = Field(default=None, description="SEO meta title generated by PIM")
    seo_description: str | None = Field(
        default=None,
        description="SEO meta description generated by PIM",
    )
    characteristics: list[MasterCharacteristicRecord] = Field(
        default_factory=list,
        description="Key-value characteristics",
    )
    photos: list[str] = Field(default_factory=list, description="Absolute public photo URLs")
    translations: dict[str, MasterProductTranslation] = Field(
        default_factory=dict,
        description="Product text translations keyed by language code, currently only 'kk'",
    )
    related: list[MasterProductRelation] = Field(
        default_factory=list,
        description=(
            "Linked products in the order the manager set them; the linked product may be absent "
            "from the partner export"
        ),
    )


class PartnerOfferRecord(BaseModel):
    """Aggregated wholesale offer of our ecosystem for one product (since 1.14.0)."""

    model_config = ConfigDict(extra="ignore", from_attributes=True)

    product_id: int = Field(..., description="Id of the product (PartnerProductRecord.id)")
    wholesale_price: float | None = Field(
        default=None,
        ge=0,
        description=(
            "Wholesale price for the partner, set manually in PIM (opt_price); "
            "null when not set — the offer is still exported"
        ),
    )
    currency: Currency = Field(default=Currency.KZT, description="Currency of wholesale_price")
    available_qty: float = Field(
        ...,
        ge=0,
        description="Our available quantity aggregated over suppliers and warehouses (min 0)",
    )
    lead_time_days: int = Field(
        ...,
        ge=0,
        description="Days from partner order to delivery (pre-order lead time), currently 3",
    )
    updated_at: datetime | None = Field(
        default=None,
        description="UTC time of the last change of price or quantity; null when unknown",
    )
